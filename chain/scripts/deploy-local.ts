import hre from "hardhat";
import { mkdirSync, writeFileSync } from "node:fs";
import path from "node:path";

// Hardhat default account #4 is the demo buyer; it receives the demo credits.
const DEMO_BUYER_INDEX = 4;
const OUT_DIR = path.resolve(__dirname, "../../web/src/generated");

async function main() {
  const publicClient = await hre.viem.getPublicClient();
  const chainId = await publicClient.getChainId();
  if (chainId !== 31337) throw new Error(`Refusing to deploy: chainId ${chainId}, expected 31337`);

  const wallets = await hre.viem.getWalletClients();
  const demoBuyer = wallets[DEMO_BUYER_INDEX].account.address;
  const ledger = await hre.viem.deployContract("FairworkLedger", [demoBuyer]);

  // The grant event is emitted in the constructor, so its block is the deploy block.
  const [granted] = await publicClient.getContractEvents({
    address: ledger.address,
    abi: ledger.abi,
    eventName: "DemoCreditsGranted",
    fromBlock: 0n,
  });
  const deployment = {
    address: ledger.address,
    deployBlock: Number(granted.blockNumber),
    chainId,
  };

  const artifact = await hre.artifacts.readArtifact("FairworkLedger");
  mkdirSync(OUT_DIR, { recursive: true });
  writeFileSync(
    path.join(OUT_DIR, "abi.ts"),
    `// Generated by chain/scripts/deploy-local.ts. Do not edit.\nexport const fairworkLedgerAbi = ${JSON.stringify(artifact.abi, null, 2)} as const;\n`,
  );
  writeFileSync(path.join(OUT_DIR, "deployment.json"), `${JSON.stringify(deployment, null, 2)}\n`);

  // eslint-disable-next-line @typescript-eslint/no-explicit-any
  const credits = await (ledger as any).read.availableOf([demoBuyer]);
  console.log(`FairworkLedger deployed at ${ledger.address} (block ${deployment.deployBlock})`);
  console.log(`Demo buyer ${demoBuyer} holds ${credits} credits`);
  console.log(`Wrote ${path.relative(process.cwd(), OUT_DIR)}/{abi.ts,deployment.json}`);
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
